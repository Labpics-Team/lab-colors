//! Портируемый некриптографический хеш общего назначения.
//!
//! Это АГНОСТИЧНЫЙ примитив ядра: он не знает ни про оттенки, ни про акценты,
//! ни про роли — только байты на входе и `u32` на выходе. Более высокий слой
//! (детерминированный выбор авто-акцента по непрозрачному ключу потребителя)
//! строится ПОВЕРХ него, но живёт вне ядра. Здесь — ровно хеш.
//!
//! # Почему FNV-1a
//!
//! Нужен маленький детерминированный хеш без зависимостей. FNV-1a — это
//! несколько строк целочисленной арифметики без таблиц; опубликованные векторы
//! и воспроизводимые hostile-входы проверяются в `tests/fnv1a_vectors.rs`.
//!
//! # Провенанс констант
//!
//! Fowler–Noll–Vo, вариант 1a, 32 бита. `offset_basis = 2166136261`
//! (0x811c9dc5), `prime = 16777619` (0x01000193). Каноническая спецификация и
//! опубликованные тест-векторы: <http://www.isthe.com/chongo/tech/comp/fnv/>.
//! Правильность зафиксирована якорными векторами `""`, `"a"`, `"foobar"` в
//! дифференциальном тесте против опубликованных значений.

/// Смещение (offset basis) FNV-1a 32-бит — начальное состояние хеша.
/// Значение хеша пустого входа равно ему (байты не обрабатываются).
const FNV1A_32_OFFSET_BASIS: u32 = 2166136261; // 0x811c9dc5

/// Простое число FNV (FNV prime) 32-бит.
const FNV1A_32_PRIME: u32 = 16777619; // 0x01000193

/// FNV-1a 32-битный хеш произвольной последовательности байт.
///
/// Детерминирован и портируем в объявленном байтовом domain. Вся арифметика —
/// обёрточная (`wrapping_*`), поэтому 32-битное переполнение
/// корректно заворачивается по модулю 2^32 и НЕ паникует даже в debug-сборке.
///
/// Вызывающий сам кодирует вход в байты (напр. `s.as_bytes()` для UTF-8) —
/// хеш семантики строки не знает.
///
/// ```
/// use labcolors_core::fnv1a_32;
/// assert_eq!(fnv1a_32(b""), 2166136261); // пустой вход == offset basis
/// assert_eq!(fnv1a_32(b"a"), 3826002220); // опубликованный вектор FNV-1a
/// ```
#[inline]
#[must_use]
pub fn fnv1a_32(bytes: &[u8]) -> u32 {
    let mut hash = FNV1A_32_OFFSET_BASIS;
    for &byte in bytes {
        hash ^= u32::from(byte);
        hash = hash.wrapping_mul(FNV1A_32_PRIME);
    }
    hash
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_is_offset_basis() {
        assert_eq!(fnv1a_32(b""), FNV1A_32_OFFSET_BASIS);
    }

    #[test]
    fn published_reference_vectors() {
        // Каноничные опубликованные векторы FNV-1a (chongo). Внешний грунт.
        assert_eq!(fnv1a_32(b"a"), 3826002220); // 0xe40c292c
        assert_eq!(fnv1a_32(b"foobar"), 3214735720); // 0xbf9cf968
    }

    #[test]
    fn deterministic() {
        assert_eq!(
            fnv1a_32(b"opaque-consumer-key"),
            fnv1a_32(b"opaque-consumer-key")
        );
    }
}
