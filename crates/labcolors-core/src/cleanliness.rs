//! Человеческая конвенция чистоты цвета: словарь исходов и гейт допуска.
//!
//! Нормативный источник — `cleanliness/DESIGN.md` соседнего репозитория
//! исследования. Здесь живёт только то, что этот контракт объявляет
//! наблюдаемым: тотальный исход оценки для слота и лестница допуска,
//! решающая, вправе ли профиль двигать цвет.
//!
//! # Чего здесь нет и не будет
//!
//! **Меры грязности.** Раздел 4 контракта запрещает единый score: величины
//! «насколько цвет грязный» не существует, потому что объявленные популяции
//! расходятся, а усреднение подменило бы предмет спора. Раздел 4 прямо называет
//! `cleanliness_score` отсутствующим в API.
//!
//! Ни один тип этого модуля не несёт числового поля чистоты, и это проверяет
//! гейт `cleanliness_no_score_field`.
//!
//! ГРАНИЦА ГЕЙТА. Этот текст дословно повторён в двух местах — в шапке
//! модуля `cleanliness` и в шапке гейта `cleanliness_no_score_field`; их
//! совпадение проверяет тест `both_boundary_texts_are_identical`.
//!
//! Гейт читает файлы модуля как текст и ловит **прямое объявление** числа:
//!
//! * поле в фигурных скобках и в кортежной форме, при любой видимости;
//! * псевдоним модуля: записанный путём (`core::primitive::u8`) —
//!   разворачивается транзитивно; параметризованный (`Carrier<f64>`) —
//!   краснеет на собственной строке объявления, в цепочку не входит;
//! * макро-вызов уровня элемента, содержащий число;
//! * **любой файл дерева модуля на любой глубине**: обход рекурсивен, и файл,
//!   добавленный завтра — хоть в каталоге подмодуля, — попадает в проверку сам.
//!
//! Чего он **не** ловит, перечислено полностью: число в типе, объявленном вне
//! модуля `cleanliness`; ассоциированную константу в `impl`-блоке (тела `impl`
//! не сканируются); число в умолчании параметра типа (`Carrier<T = u8>`); и
//! любую индирекцию, которую текстовый разбор не разворачивает.
//!
//! Гейт останавливает **случайное** введение меры, а барьером против
//! намеренного обхода не является и им не притворяется: текстовый сканер таким
//! барьером быть не может.
//!
//! **Коррекции цвета.** Право двигать цвет даёт только верхняя ступень
//! лестницы допуска раздела 9, [`AdmittedLevelV1::AutoAction`]. Её носитель
//! [`AutoActionAdmissionV1`] необитаем, потому что ни один release условиям
//! допуска не удовлетворяет, — значит права не существует, и это проверяет
//! компилятор.
//!
//! Поэтому **сегодня** для движимого слота в режимах `lint` и `auto`
//! наблюдается [`QualityOutcomeV1::UnchangedNoAdmittedProfile`] — названный
//! отчёт, а не молчание. Утверждение описывает текущее состояние доказательной
//! базы и истекает вместе с ним; в день первого допуска его придётся
//! пересмотреть (перечень таких мест — в модуле `admission`). Режим `off`
//! значения `QualityOutcome` не порождает вовсе.
//!
//! # Чистота цвета и чистота оттенка — разные конструкты
//!
//! В крейте уже есть `neutral::HUE_PURITY_*` — это **чистота оттенка**,
//! геометрическая величина расстояния от нейтральной оси. Настоящий модуль
//! про **воспринимаемую чистоту цвета** (clean–dirty), конструкт из
//! колориметрических исследований. Смешивать их запрещено: первое считается
//! из координат, второе не считается вовсе, потому что меры не существует.

