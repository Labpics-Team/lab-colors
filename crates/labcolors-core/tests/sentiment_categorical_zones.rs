//! Задача Волны 1 «правда»: категориальные зоны хью сентиментов вместо жёсткого
//! лока сепарации от бренда.
//!
//! ПОЧЕМУ этот тест существует (класс бага, не заплатка): прежний закон форсировал
//! КАЖДЫЙ сентимент отойти от бренда минимум на `s_min`≈20.7° как ЖЁСТКУЮ
//! легальность. Для бренда labui (синий, Oklab hue ~253–263°) это толкало Info
//! (прототип синий 259.89°, якорь #3E87FF) в ПУРПУР (#7579FE и т.п.) — хотя
//! семантически инфо-зона легитимно ВКЛЮЧАЕТ синий, и совпадение инфо с брендовым
//! синим НЕ ошибка (решение владельца).
//!
//! Заземление зон (лестница объективизации):
//! - Существование стабильного фокуса на категорию и РАЗМЫТОСТЬ границ —
//!   (b) GROUNDED: Berlin & Kay (1969); Kay & McDaniel (1978, fuzzy-set модель,
//!   DOI 10.1353/lan.1978.0035); Regier, Kay & Cook (2005, PNAS 102(23):8386,
//!   DOI 10.1073/pnas.0503281102 — фокусы кластеризуются ТЕСНЕЕ границ).
//! - Литература НЕ даёт основания форсировать сепарацию от бренда — только
//!   держать оттенок ВНУТРИ своей категории. Значит правило = зона, лок = исключение.
//! - Конкретный Oklab-край зоны — (e) DESIGN-CHOICE (все источники до Oklab;
//!   честная граница при размытой реальной — середина к соседнему фокусу).
//!
//! Тест написан ДО реализации (TDD RED): на текущем законе п.1 падает
//! (Info уходит в пурпур), после закона зон — зелёный.

use labcolors_core::oklch_from_hex;
use labcolors_core::sentiment::resolve_config_sentiment_solid;

/// Oklab-оттенок (градусы) отгружаемого hex.
fn hue(hex: &str) -> f64 {
    oklch_from_hex(hex).expect("валидный hex")[2]
}
/// Кратчайшее угловое расстояние (градусы) по кругу оттенка.
fn ang(a: f64, b: f64) -> f64 {
    let d = (a - b).rem_euclid(360.0);
    if d > 180.0 { 360.0 - d } else { d }
}

// Якоря сентимент-семейств labui (Figma Accent/*, Light-mode, замер 2026-06-30).
const RED: &str = "#FF3B30";
const ORANGE: &str = "#FFA100";
const GREEN: &str = "#34C759";
const BLUE: &str = "#3E87FF";

/// Пер-темные бренды labui (Figma `Accent/Brand`): свет/тьма/light-ic/dark-ic.
/// Под законом Волны 1 бренд оттенок сентимента НЕ смещает — цикл по брендам
/// доказывает именно brand-независимость (результат одинаков для всех).
const LABUI_BRANDS: [&str; 4] = ["#007AFF", "#4A8FFF", "#0040DD", "#409CFF"];

/// ЦЕНТРАЛЬНОЕ требование владельца: Info отдыхает на своём синем якоре при
/// брендовом синем во ВСЕХ 4 режимах labui — совпадение инфо↔бренд легитимно,
/// не пурпур. Порог 2° >> квантование, << прежнего смещения ≈13–20°.
#[test]
fn info_rests_on_blue_anchor_under_the_blue_labui_brand_all_modes() {
    let proto = hue(BLUE); // 259.89°
    for brand_hex in LABUI_BRANDS {
        let brand_hue = hue(brand_hex);
        // Новый закон: бренд игнорируется — Info отдыхает на синем прототипе во
        // всех 4 режимах (порог 2° >> квантование).
        let solid = resolve_config_sentiment_solid(BLUE, 1.0, None).expect("Info резолвится");
        let got = hue(&solid);
        assert!(
            ang(got, proto) <= 2.0,
            "Info при бренде {brand_hex} (hue {brand_hue:.2}°) обязан отдыхать на синем \
             якоре {proto:.2}°, получено {got:.2}° (solid {solid}) — инфо-зона включает синий, \
             совпадение с брендом не ошибка"
        );
    }
}

/// КЛАСС инварианта (обобщение): для ЛЮБОГО сентимента, когда бренд совпадает с
/// оттенком его собственного якоря, сентимент отдыхает на якоре — совпадение с
/// брендом внутри своей зоны легитимно для всех категорий (инверсия по всем
/// сентиментам, как требует задача).
#[test]
fn every_sentiment_rests_when_brand_coincides_with_its_own_anchor() {
    for anchor in [RED, ORANGE, GREEN, BLUE] {
        let proto = hue(anchor);
        // hue_floor только у warning (оранжевый); для якоря orange 68.61° > 45° он
        // не кусается, оставляем None у остальных, Some(45) у orange для честности.
        let floor = if anchor == ORANGE { Some(45.0) } else { None };
        let solid = resolve_config_sentiment_solid(anchor, 1.0, floor).expect("резолвится");
        let got = hue(&solid);
        assert!(
            ang(got, proto) <= 2.0,
            "сентимент-якорь {anchor} при бренде НА своём оттенке {proto:.2}° обязан \
             отдыхать (получено {got:.2}°) — сепарация от бренда больше не форсируется"
        );
    }
}

/// Warning остаётся в оранжевой зоне и НЕ сползает в красную (danger) — пол 45°
/// как задокументированное исключение сохраняется при любом бренде.
#[test]
fn warning_stays_in_the_orange_zone_above_the_floor_all_brands() {
    let mut brand = 0.0_f64;
    while brand < 360.0 {
        // Бренд в новом законе игнорируется; цикл держит инвариант «Warning над
        // полом 45°» независимым от него.
        let solid =
            resolve_config_sentiment_solid(ORANGE, 1.0, Some(45.0)).expect("Warning резолвится");
        let got = hue(&solid);
        assert!(
            got >= 45.0 - 1e-6,
            "Warning оттенок {got:.2}° при бренде {brand:.1}° ниже пола 45° (сполз в красную зону)"
        );
        brand += 1.0;
    }
}
