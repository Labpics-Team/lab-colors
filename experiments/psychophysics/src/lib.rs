//! # psychophysics — харнесс психофизической калибровки констант lab-colors
//!
//! Инструмент (не человеческая сессия) для мишени #1 реестра остатка:
//! `PAIR_CROSSOVER_Y = 0.30` (см. `docs/empirical-residue.md` §1). Даёт
//! воспроизводимый конвейер «стимул → сбор → оценка → вердикт», готовый к запуску
//! владельцем с ≥ 15 наблюдателями.
//!
//! ## Модули
//! - [`rng`] — детерминированный ГПСЧ (SplitMix64): единый источник случайности.
//! - [`json`] — минимальный JSON без зависимостей (чтение паспорта, экспорт).
//! - [`color`] — sRGB/линейный свет, WCAG-люминанс, свотч на заданный Y.
//! - [`passport`] — чтение замороженного паспорта labui → фирменные семьи.
//! - [`stimulus`] — детерминированный манифест 2AFC-сессии из seed.
//! - [`html`] — рендер автономного офлайн-раннера со встроенным манифестом.
//! - [`logistic`] — MLE-подгонка психометрики (IRLS) и PSE.
//! - [`analysis`] — bootstrap 95% CI PSE и вердикт по критерию приёмки.
//! - [`synthetic`] — синтетический наблюдатель для замка честности.
//!
//! ## Поток
//! `generate` строит манифест (`stimulus`) и раннер (`html`); наблюдатель проходит
//! 2AFC в браузере и экспортирует сырой JSON; `analyze` подгоняет логистику
//! (`logistic`), считает bootstrap CI и выносит вердикт (`analysis`). Замок
//! честности (`synthetic` + `tests/self_test.rs`) доказывает, что конвейер
//! восстанавливает известный PSE, а не подтверждает произвольное значение.
//!
//! Зависимостей рантайма — ноль (правило репо, issue #29): вся математика
//! (логистика, bootstrap, JSON, ГПСЧ) написана руками на `std`.

